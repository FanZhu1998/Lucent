std::string_view tiff_field_type_name(std::uint16_t type) noexcept {
    switch (static_cast<TiffFieldType>(type)) {
        case TiffFieldType::Byte:
            return "BYTE";
        case TiffFieldType::Ascii:
            return "ASCII";
        case TiffFieldType::Short:
            return "SHORT";
        case TiffFieldType::Long:
            return "LONG";
        case TiffFieldType::Rational:
            return "RATIONAL";
        case TiffFieldType::SByte:
            return "SBYTE";
        case TiffFieldType::Undefined:
            return "UNDEFINED";
        case TiffFieldType::SShort:
            return "SSHORT";
        case TiffFieldType::SLong:
            return "SLONG";
        case TiffFieldType::SRational:
            return "SRATIONAL";
        case TiffFieldType::Float:
            return "FLOAT";
        case TiffFieldType::Double:
            return "DOUBLE";
        case TiffFieldType::Ifd:
            return "IFD";
        case TiffFieldType::Long8:
            return "LONG8";
        case TiffFieldType::SLong8:
            return "SLONG8";
        case TiffFieldType::Ifd8:
            return "IFD8";
    }
    return "unknown";
}

